// ---------------- schedule ----------------
// time of post n of stream k ('g' Peachgram / 'p' Pcard), in game-clock minutes
export function slotAt(k, n) {
  const d = Math.floor(n / PER),
    base = SLOTS[k][n % PER];
  return d * 1440 + base + (hashN(k === 'g' ? 11 : 22, n) % 31) - 15;
}
// the first post that comes after `clock`
export function nextIndex(k, clock) {
  let n = Math.max(0, Math.floor(clock / 1440) - 1) * PER;
  while (slotAt(k, n) <= clock) n++;
  return n;
}
const firstIndex = (k) => nextIndex(k, START);
// shuffled order of `len` items for one pass; neighbours try not to share `key`
const ORDERS = new Map();
function order(k, pass, len, key) {
  const id = `${k}${pass}`;
  if (ORDERS.has(id)) return ORDERS.get(id);
  const R = rngOf(hashN(2026, k === 'g' ? 1 : 2, pass)),
    a = [...Array(len).keys()];
  for (let i = len - 1; i > 0; i--) {
    const j = Math.floor(R() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  for (let i = 1; i < len; i++)
    if (key(a[i]) === key(a[i - 1])) {
      for (let j = i + 1; j < len; j++)
        if (key(a[j]) !== key(a[i - 1])) {
          [a[i], a[j]] = [a[j], a[i]];
          break;
        }
    }
  if (ORDERS.size > 8) ORDERS.delete(ORDERS.keys().next().value);
  ORDERS.set(id, a);
  return a;
}
export function gramPost(n) {
  const L = LINES.length,
    pass = Math.floor(n / L),
    i = order('g', pass, L, (x) => LINES[x].who)[n % L],
    line = LINES[i];
  return {
    id: `gn${n}`,
    who: line.who,
    img: line.img,
    cap: line.t,
    at: slotAt('g', n),
    likes: 15 + (hashN(n, 7) % 260),
  };
}
export function pcardPost(n) {
  const P = POSTS.length,
    pass = Math.floor(n / P),
    p = POSTS[order('p', pass, P, (x) => POSTS[x].topic)[n % P]];
  return {
    id: `pn${n}`,
    t: p.t,
    b: p.b,
    c: p.c.map((x, j) => `B${j + 1} ${x}`),
    at: slotAt('p', n),
    n: 3 + (hashN(n, 9) % 90),
  };
}
// the newest `count` posts at or before `clock` (generated ones only; they start after the game's opening moment)
export function postsUpTo(k, clock, count = 40) {
  const out = [],
    first = firstIndex(k),
    make = k === 'g' ? gramPost : pcardPost;
  for (let n = nextIndex(k, clock) - 1; n >= first && out.length < count; n--) out.push(make(n));
  return out;
}
