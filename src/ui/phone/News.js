const CATS = { 校園: '#2f6bff', 美食: '#ff7a1a', 生活: '#1f9d55', 科技: '#7a4bff', 娛樂: '#d62976', 社會: '#5b6270', 財經: '#c81e2a' };
const fill = (s, st) => s.replace(/\{n\}/g, st.name).replace(/\{c\}/g, st.code).replace(/\{i\}/g, st.ind);

// all 3 articles of a game day (pure)
const CACHE = new Map();
export function newsForDay(d) {
  if (CACHE.has(d)) return CACHE.get(d);
  const out = [];
  const R = rngOf(hashN(SEED, d, 77));
  const usedLife = new Set();
  for (let k = 0; k < 3; k++) {
    const at = d * 1440 + (d === 0 && k === 0 ? 6 * 60 : SLOTS[k]);
    const id = `${d}-${k}`;
    if (d === 0 && k === 0) { out.push({ id, d, at, ...FIRST, color: CATS[FIRST.cat] }); continue; }
    const r = R();
    if (r < 0.5) { // company news, moves the stock
      const list = STOCKS.filter(s => s.code !== 'PYL');
      const st = list[Math.floor(R() * list.length)], good = R() < 0.55;
      const T = (good ? GOOD : BAD)[Math.floor(R() * (good ? GOOD : BAD).length)];
      const pct = (good ? 1 : -1) * (0.03 + R() * 0.05);
      out.push({ id, d, at, cat: '財經', color: CATS.財經, emoji: good ? '📈' : '📉', title: fill(T.t, st), body: T.b.map(x => fill(x, st)), stock: { code: st.code, pct } });
    } else {
      let i = Math.floor(R() * LIFE.length); while (usedLife.has(i)) i = (i + 1) % LIFE.length; usedLife.add(i);
      const L = LIFE[i];
      out.push({ id, d, at, cat: L.cat, color: CATS[L.cat] || '#5b6270', emoji: L.e, title: L.t, body: L.b });
    }
  }
  CACHE.set(d, out);
  return out;
}
// published articles up to the game clock, newest first (the last `days` days)
export function publishedNews(clock, days = 14) {
  const today = Math.floor(clock / 1440), out = [];
  for (let d = Math.max(0, today - days + 1); d <= today; d++) for (const a of newsForDay(d)) if (a.at <= clock) out.push(a);
  return out.sort((a, b) => b.at - a.at);
}
// stock effects that land on trading day d: [{ code, pct, at (minute of day; OPEN = an opening gap) }]
export function newsEffects(d) {
  if (!isTradingDay(d) || d < 0) return [];
  const out = [];
  for (let nd = Math.max(0, d - 5); nd <= d; nd++) for (const a of newsForDay(nd)) {
    if (!a.stock) continue;
    const m = a.at - nd * 1440;
    let land = nd; // first trading day whose session the news can still move
    if (!isTradingDay(nd) || m >= CLOSE) { land = nd + 1; while (!isTradingDay(land)) land++; }
    if (land !== d) continue;
    out.push({ code: a.stock.code, pct: a.stock.pct, at: land === nd && m > OPEN ? m : OPEN, id: a.id });
  }
  return out;
}
