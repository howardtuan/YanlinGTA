// 一片雜木林：在 s0～s1、離線 o0～o1 的範圍裡均勻撒 n 棵樹（位置用 Halton 數列算，固定不變）；回傳一串 ['tree', s, off, 高] 給 items 用
const grove = (s0, s1, o0, o1, n) => {
  const hal = (j, b) => {
    let f = 1,
      v = 0;
    for (; j > 0; j = Math.floor(j / b)) {
      f /= b;
      v += f * (j % b);
    }
    return v;
  };
  return Array.from({ length: n }, (_, j) => [
    'tree',
    +(s0 + (s1 - s0) * hal(j + 1, 2)).toFixed(1),
    +(o0 + (o1 - o0) * hal(j + 1, 3)).toFixed(1),
    +(9 + 3.5 * hal(j + 1, 5)).toFixed(1),
  ]);
};

