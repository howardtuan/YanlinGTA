export function pzAt(s) {
  const R = PZ_ROAD;
  let acc = 0;
  for (let i = 0; i < R.length - 1; i++) {
    const a = R[i],
      b = R[i + 1],
      L = Math.hypot(b[0] - a[0], b[1] - a[1]);
    if (s <= acc + L || i === R.length - 2) {
      const t = (s - acc) / L;
      return {
        x: a[0] + (b[0] - a[0]) * t,
        z: a[1] + (b[1] - a[1]) * t,
        ux: (b[0] - a[0]) / L,
        uz: (b[1] - a[1]) / L,
      };
    }
    acc += L;
  }
}
// 每一格的區域座標：原點在立面線的起點，+x 沿立面（side -1 時朝 s 變小的方向，立面才對著街），+z 離開街道
export function pzLotFrame([s0, s1, side, sp]) {
  const m = pzAt((s0 + s1) / 2),
    w = s1 - s0,
    nx = -m.uz * side,
    nz = m.ux * side;
  const ax = side > 0 ? m.ux : -m.ux,
    az = side > 0 ? m.uz : -m.uz;
  const set = (sp && sp.set) || setAt(side);
  return {
    ox: m.x + nx * set - (ax * w) / 2,
    oz: m.z + nz * set - (az * w) / 2,
    ang: Math.atan2(az, ax),
    w,
    apron: Math.max(0.6, Math.min(sp && sp.apron !== undefined ? sp.apron : 9, set - halfAt(side))),
  };
}
export function pzFootprints() {
  const fp = PZ_ST.fences.map(([s0, s1, side]) => {
    const { ox, oz, ang, w, apron } = pzLotFrame([s0, s1, side, { set: setAt(side) + 0.35 }]),
      c = Math.cos(ang),
      s = Math.sin(ang),
      p = (x, z) => [ox + x * c - z * s, oz + x * s + z * c];
    return [p(-0.1, -apron - 0.2), p(w + 0.1, -apron - 0.2), p(w + 0.1, 1.8), p(-0.1, 1.8)];
  });
  return fp.concat(
    PZ_ST.lots.map((L) => {
      const { ox, oz, ang, w, apron } = pzLotFrame(L),
        c = Math.cos(ang),
        s = Math.sin(ang),
        d = L[3].d || 10;
      const p = (x, z) => [ox + x * c - z * s, oz + x * s + z * c];
      return [p(-0.1, -apron - 0.2), p(w + 0.1, -apron - 0.2), p(w + 0.1, d), p(-0.1, d)];
    })
  );
}
