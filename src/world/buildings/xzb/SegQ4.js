//   兩側牆腳原本是 1～3 m 的草地，實景是水泥地一路鋪到牆邊，補鋪水泥地。
// 側牆的東西用原本那棟的 Kit 畫（側牆就是那格的 x=0 或 x=W 面），所以不會和樓錯位；外面刷一層牆色把原本自動長的窗蓋掉，再照實景放窗。
// 不加機車（停放機車會改到全圖機車雜湊）。看不清的小字不放。
import { NC, seg, polyBlock } from './qkit.js';

const R = 'Q185';
// 巷子座標（s 沿巷子、n 往 +1 側＝西側）換世界座標；和 StreetXinzhongbei.js 的 XZ_REF.Q185 同一條線
const A = [-404.2, -93.2],
  B = [-388.6, -65.4],
  LEN = Math.hypot(B[0] - A[0], B[1] - A[1]),
  UX = (B[0] - A[0]) / LEN,
  UZ = (B[1] - A[1]) / LEN;
const P = (s, n) => [A[0] + s * UX - n * UZ, A[1] + s * UZ + n * UX];

const RUST = '#8a5a3a',
  BAND = '#8e979c',
  CONC = '#a3a39c';

// 側牆的畫筆：k 是那棟原本的 Kit，側牆在 x = x0，dir 是側牆朝外（朝巷子）的 x 方向；
// u 是沿側牆的 Kit z 座標（離開原本那條街的方向），o 是離牆面往巷子多遠
const face = (C, k, x0, dir) => {
  const X = (o) => x0 + dir * o;
  const F = {
    box: (u0, u1, y0, y1, o0, o1, hex, o = NC) =>
      k.box(Math.min(X(o0), X(o1)), Math.max(X(o0), X(o1)), y0, y1, u0, u1, hex, o),
    plane: (tex, w, h, u, y, o, opt) =>
      k.plane(tex, w, h, X(o), y, u, dir > 0 ? Math.PI / 2 : -Math.PI / 2, opt),
    // 鐵窗：深色玻璃＋白鐵窗格
    win: (u, y, w, h, bar = '#e6e6e0') => {
      F.box(
        u - w / 2 - 0.06,
        u + w / 2 + 0.06,
        y - h / 2 - 0.06,
        y + h / 2 + 0.06,
        0,
        0.04,
        '#d8d8d2'
      );
      F.box(u - w / 2, u + w / 2, y - h / 2, y + h / 2, 0.04, 0.06, '#3c4650');
      for (let v = u - w / 2; v <= u + w / 2 + 0.01; v += 0.14)
        F.box(v, v + 0.025, y - h / 2, y + h / 2, 0.06, 0.1, bar);
      for (const yy of [y - h / 2, y, y + h / 2])
        F.box(u - w / 2, u + w / 2, yy - 0.02, yy + 0.02, 0.06, 0.1, bar);
    },
    // 窗型冷氣：外殼＋前面一片散熱格
    ac: (u, y) => {
      F.box(u - 0.4, u + 0.4, y, y + 0.55, 0, 0.5, '#e4e4de');
      F.box(u - 0.32, u + 0.32, y + 0.08, y + 0.47, 0.5, 0.52, '#9aa0a2');
      F.box(u - 0.35, u + 0.35, y - 0.06, y, 0, 0.45, '#8a8d8f');
    },
    // 一團球（樹葉、盆栽的葉子）
    ball: (u, y, o, r, hex) => {
      const g = new C.THREE.SphereGeometry(r, 7, 5);
      g.scale(1, 0.8, 1);
      g.translate(X(o), y, u);
      k._part(C.VC, C.paintGeo(g, hex));
    },
    // 鋪面：牆腳到巷子路緣，o0／o1 是 u0／u1 兩端牆面到路緣的距離（貼地形，頂點照各點地面高度）
    pave: (u0, u1, oa, ob) => {
      const pts = [
        [X(0), u0],
        [X(oa), u0],
        [X(ob), u1],
        [X(0), u1],
      ];
      // 和其他方塊一起合併（finishRow），要有 index、uv、normal 才合得起來
      const pos = [];
      for (const [x, z] of pts) pos.push(x, C.groundY(k, x, z) + 0.04, z);
      const g = new C.THREE.BufferGeometry();
      g.setAttribute('position', new C.THREE.Float32BufferAttribute(pos, 3));
      g.setAttribute('uv', new C.THREE.Float32BufferAttribute([0, 0, 1, 0, 1, 1, 0, 1], 2));
      g.setIndex([0, 1, 2, 0, 2, 3]);
      g.computeVertexNormals();
      if (g.attributes.normal.array[1] < 0) g.setIndex([0, 2, 1, 0, 3, 2]); // 兩個三角形都要朝上
      g.computeVertexNormals();
      k._part(C.VC, C.paintGeo(g, CONC));
    },
  };
  return F;
};

// 盆栽：深色花盆＋一團綠葉
const pot = (F, u, o, r = 0.28, hex = '#3f7a3a') => {
  F.box(u - r * 0.7, u + r * 0.7, 0, r * 1.3, o - r * 0.7, o + r * 0.7, '#7a4a32');
  F.ball(u, r * 1.9, o, r * 1.1, hex);
};

